/**
 * Pure Mermaid Renderer + Label Sanitizer (blast-radius-diagram Slice 1)
 *
 * Deterministic, synchronous mermaid `flowchart TD` builder over an
 * explicit node/edge input. NO pipeline dependency — testable standalone.
 *
 * Injection safety (design D6): file names come from the attacker-controlled
 * PR head. Three closed layers keep hostile bytes out of the diagram:
 *   1. `sanitizeMermaidLabel` — allowlist charset `[A-Za-z0-9._/+ -]`,
 *      everything else collapses to `_`, length capped at 80 (`…` on
 *      truncation). Quotes, backticks, `<`, `>`, `|`, newlines, unicode
 *      cannot survive, so a quoted label can never be escaped and `-->`
 *      can never become edge syntax (quotes are unavailable).
 *   2. Node ids (`n0`…) and cluster ids (`c0`…) are generated by this
 *      module's own templates — never derived from file paths.
 *   3. Edge/subgraph lines contain zero untrusted data; legend text is
 *      trusted literals + booleans/numbers.
 *
 * Determinism (design D7): nodes sorted path-asc with id = sorted index,
 * edges sorted (from-id asc, to-id asc), clusters sorted asc with nodes
 * path-asc inside. NO `Set` iteration reaches the output — every emitted
 * sequence is spread → sorted → emitted, so identical inputs produce
 * byte-identical mermaid across runs.
 *
 * Caps (design D2): 25 nodes / 40 edges enforced here as well — render-side
 * defensive only; production inputs arrive pre-capped from the builder
 * (Slice 2), which enforces the same caps at BUILD time. `format.ts` and
 * the dashboard are render-only and never truncate.
 */

import {
  BLAST_RADIUS_DIAGRAM_MAX_JSON_CHARS,
  type BlastRadiusDiagram,
  type BlastRadiusDiagramEdge,
  type BlastRadiusDiagramMeta,
  type BlastRadiusDiagramNode,
  type BlastRadiusDiagramNodeRole,
  MAX_DIAGRAM_EDGES,
  MAX_DIAGRAM_LABEL_CHARS,
  MAX_DIAGRAM_NODES,
} from './schema.js';

// ─── Inputs ─────────────────────────────────────────────────────

/** Raw (unsanitized) node input — `path` is attacker-controlled. */
export interface MermaidNodeInput {
  path: string;
  role: BlastRadiusDiagramNodeRole;
}

/**
 * Edge input by path. `from` = importer, `to` = importee (`→` = imports,
 * matching `node.imports` / reverse-index orientation, design D1).
 */
export interface MermaidEdgeInput {
  from: string;
  to: string;
}

/** Flags threaded through from the blast-radius metadata. */
export interface MermaidMetaInput {
  stale: boolean;
  exceededCap: boolean;
}

// ─── Sanitizer ──────────────────────────────────────────────────

/**
 * Cluster label for root files (no `/` in the path).
 * Emitted only inside this module's own quoted templates.
 */
export const MERMAID_ROOT_CLUSTER = '(root)';

/** Every character outside `[A-Za-z0-9._/+ -]` collapses to `_`. */
const MERMAID_DISALLOWED_CHARS = /[^A-Za-z0-9._/+ -]/g;

/**
 * Sanitize an attacker-controlled file path for use as a mermaid node
 * label. Allowlist-only (a per-char escape map would miss vectors): every
 * character outside `[A-Za-z0-9._/+ -]` becomes `_`, then the result is
 * capped at `MAX_DIAGRAM_LABEL_CHARS` (80) characters — on truncation the
 * final character is `…`, the ONLY non-allowlist byte this module ever
 * emits, produced solely by its own truncation template (never reachable
 * from input characters).
 */
export function sanitizeMermaidLabel(path: string): string {
  const allowed = path.replace(MERMAID_DISALLOWED_CHARS, '_');
  if (allowed.length <= MAX_DIAGRAM_LABEL_CHARS) {
    return allowed;
  }
  return `${allowed.slice(0, MAX_DIAGRAM_LABEL_CHARS - 1)}…`;
}

/**
 * Top-level directory of a path (first segment) — design D5 cluster
 * granularity. Directory-derived segments are sanitized with the same
 * allowlist as node labels (a hostile top-level dir cannot smuggle quotes
 * or `>` into a subgraph title); the `'(root)'` literal for root files is
 * a trusted module constant and is returned unsanitized (parens are
 * exactly what the legend/subgraph title should show).
 */
export function clusterOfPath(path: string): string {
  const slash = path.indexOf('/');
  if (slash === -1) return MERMAID_ROOT_CLUSTER;
  return sanitizeMermaidLabel(path.slice(0, slash));
}

// ─── Deterministic comparison ───────────────────────────────────

/**
 * Locale-independent, UTF-16 code-unit ordering — stable across runs,
 * machines, and ICU versions (never `localeCompare`).
 */
function comparePaths(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

// ─── Renderer ───────────────────────────────────────────────────

/**
 * Build the complete `BlastRadiusDiagram` (mermaid source + capped lists +
 * meta) from raw node/edge inputs.
 *
 * Pipeline:
 *   1. Dedupe nodes by path (first occurrence wins the role) and sort
 *      path-asc; ids `n0…` are the sorted index.
 *   2. Defensive node cap (`MAX_DIAGRAM_NODES`): keep the first 25 in
 *      sorted order, record `truncated` + `clusterCounts` (omitted per
 *      cluster) when input exceeded it.
 *   3. Map edges path→id, drop dangling edges (endpoint not in the kept
 *      node set), dedupe, sort (from-id asc, to-id asc), cap at
 *      `MAX_DIAGRAM_EDGES` (edge truncation also sets `truncated`).
 *   4. Emit mermaid in the pinned order (D7): header → classDefs →
 *      subgraphs (cluster asc, nodes path-asc inside) → `class` lines
 *      (role order changed, dependent, test) → edges.
 *
 * Empty node input yields `mermaid: ''` and empty lists — the formatter
 * treats that as "no section" (zero bytes contributed).
 *
 * Pure and synchronous; never throws on hostile input (the allowlist is
 * closed). The only throw path is the build-time JSON-size invariant,
 * which the Slice-2 builder — not this renderer — owns.
 */
export function renderMermaidDiagram(
  nodes: MermaidNodeInput[],
  edges: MermaidEdgeInput[],
  meta: MermaidMetaInput = { stale: false, exceededCap: false },
): BlastRadiusDiagram {
  // 1. Dedupe by path, then sort path-asc (deterministic id assignment).
  const seen = new Set<string>();
  const unique: MermaidNodeInput[] = [];
  for (const node of nodes) {
    if (seen.has(node.path)) continue;
    seen.add(node.path);
    unique.push(node);
  }
  unique.sort((a, b) => comparePaths(a.path, b.path));

  // 2. Defensive node cap — production inputs arrive pre-capped (Slice 2).
  let nodeTruncated = false;
  const clusterCounts: Record<string, number> = {};
  let kept = unique;
  if (unique.length > MAX_DIAGRAM_NODES) {
    nodeTruncated = true;
    kept = unique.slice(0, MAX_DIAGRAM_NODES);
    for (const omitted of unique.slice(MAX_DIAGRAM_NODES)) {
      const cluster = clusterOfPath(omitted.path);
      clusterCounts[cluster] = (clusterCounts[cluster] ?? 0) + 1;
    }
  }

  const idByPath = new Map<string, string>();
  const diagramNodes: BlastRadiusDiagramNode[] = kept.map((node, index) => {
    const id = `n${index}`;
    idByPath.set(node.path, id);
    return {
      id,
      label: sanitizeMermaidLabel(node.path),
      role: node.role,
      cluster: clusterOfPath(node.path),
    };
  });

  // 3. Edges: path→id, drop dangling, dedupe, sort, cap. Ids are this
  // module's own `n<index>` strings — sort by NUMERIC index, never
  // lexicographically ('n10' < 'n2' as strings would scramble D7 order).
  const indexById = new Map<string, number>(kept.map((_, index) => [`n${index}`, index]));
  const edgeSeen = new Set<string>();
  const diagramEdges: BlastRadiusDiagramEdge[] = [];
  for (const edge of edges) {
    const from = idByPath.get(edge.from);
    const to = idByPath.get(edge.to);
    if (from === undefined || to === undefined || from === to) continue; // dangling / self
    const key = `${from}\u0000${to}`;
    if (edgeSeen.has(key)) continue;
    edgeSeen.add(key);
    diagramEdges.push({ from, to });
  }
  const numericId = (id: string): number => indexById.get(id) ?? Number.MAX_SAFE_INTEGER;
  diagramEdges.sort(
    (a, b) => numericId(a.from) - numericId(b.from) || numericId(a.to) - numericId(b.to),
  );

  let edgeTruncated = false;
  let finalEdges = diagramEdges;
  if (diagramEdges.length > MAX_DIAGRAM_EDGES) {
    edgeTruncated = true;
    finalEdges = diagramEdges.slice(0, MAX_DIAGRAM_EDGES);
  }

  const diagramMeta: BlastRadiusDiagramMeta = {
    stale: meta.stale,
    exceededCap: meta.exceededCap,
    truncated: nodeTruncated || edgeTruncated,
    ...(nodeTruncated ? { clusterCounts } : {}),
  };

  return {
    mermaid: kept.length === 0 ? '' : emitMermaid(diagramNodes, finalEdges),
    nodes: diagramNodes,
    edges: finalEdges,
    meta: diagramMeta,
  };
}

// ─── Mermaid emission ───────────────────────────────────────────

/** Role order for `class` lines: actionable first (changed → dependent → test). */
const ROLE_ORDER: readonly BlastRadiusDiagramNodeRole[] = ['changed', 'dependent', 'test'];

/** Per-role classDef styles (trusted literals — no untrusted data). */
const ROLE_CLASS_DEF: Record<BlastRadiusDiagramNodeRole, string> = {
  changed: 'fill:#fef3c7,stroke:#d97706,stroke-width:2px',
  dependent: 'fill:#dbeafe,stroke:#2563eb',
  test: 'fill:#dcfce7,stroke:#16a34a',
};

/**
 * Emit the mermaid source in the pinned D7 order. All ids, keywords, and
 * styles come from this template; the only input-derived bytes are the
 * allowlist-sanitized labels (always double-quoted) and cluster names.
 */
function emitMermaid(nodes: BlastRadiusDiagramNode[], edges: BlastRadiusDiagramEdge[]): string {
  const lines: string[] = ['flowchart TD'];
  for (const role of ROLE_ORDER) {
    lines.push(`  classDef ${role} ${ROLE_CLASS_DEF[role]}`);
  }

  // Subgraphs: cluster asc, nodes path-asc (== id asc) inside.
  const clusters = new Map<string, BlastRadiusDiagramNode[]>();
  for (const node of nodes) {
    const bucket = clusters.get(node.cluster);
    if (bucket) bucket.push(node);
    else clusters.set(node.cluster, [node]);
  }
  const clusterNames = [...clusters.keys()].sort(comparePaths);
  clusterNames.forEach((cluster, index) => {
    lines.push(`  subgraph c${index}["${cluster}"]`);
    for (const node of clusters.get(cluster) ?? []) {
      lines.push(`    ${node.id}["${node.label}"]`);
    }
    lines.push('  end');
  });

  // class assignments: one line per role, ids asc.
  for (const role of ROLE_ORDER) {
    const ids = nodes.filter((n) => n.role === role).map((n) => n.id);
    if (ids.length === 0) continue;
    lines.push(`  class ${ids.join(',')} ${role}`);
  }

  // edges: already sorted (from-id asc, to-id asc).
  for (const edge of edges) {
    lines.push(`  ${edge.from} --> ${edge.to}`);
  }

  return lines.join('\n');
}

/**
 * Build-time JSON-size invariant (design D2): asserts the serialized
 * diagram fits `BLAST_RADIUS_DIAGRAM_MAX_JSON_CHARS`. Called by the
 * Slice-2 builder AFTER capping — with the caps enforced the worst case
 * is ~6-8 KB, so a violation means a bug, and the builder throws so the
 * pipeline can degrade to counts-only (never persist an oversized blob).
 */
export function assertDiagramJsonBudget(diagram: BlastRadiusDiagram): void {
  const size = JSON.stringify(diagram).length;
  if (size > BLAST_RADIUS_DIAGRAM_MAX_JSON_CHARS) {
    throw new Error(
      `blast-radius diagram exceeds JSON budget: ${size} > ${BLAST_RADIUS_DIAGRAM_MAX_JSON_CHARS} chars`,
    );
  }
}
